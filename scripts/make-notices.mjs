// Generates THIRD-PARTY-NOTICES.md from the licence files of the libraries that end up inside the app bundle,
// plus the licence notices for the data we ship. Run with `npm run notices` after changing dependencies.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
// Runtime libraries bundled into out/ (all are listed as devDependencies because Vite bundles them), with their own runtime dependencies.
const packages = [
  "chart.js",
  "@kurkle/color",
  "d3-geo",
  "d3-array",
  "internmap",
  "topojson-client",
  "commander",
  "world-atlas",
  "zod",
];

const sections = packages.map((name) => {
  const dir = join(root, "node_modules", name);
  const meta = JSON.parse(readFileSync(join(dir, "package.json"), "utf-8"));
  const file = readdirSync(dir).find((f) => /^licen[sc]e/i.test(f));
  if (!file) throw new Error(`No licence file found for ${name}`);
  const text = readFileSync(join(dir, file), "utf-8").trim();
  return `### ${name} ${meta.version} (${meta.license})\n\n\`\`\`text\n${text}\n\`\`\``;
});

const unicode = readFileSync(
  join(root, "docs", "licenses", "unicode-license-v3.txt"),
  "utf-8",
).trim();

const out = `# Third-party notices

ResistanceScope's own code is MIT licensed (see LICENSE). The app bundles the libraries and data below.
This file is generated by \`npm run notices\`; do not edit it by hand.

The installed app also contains Electron and Chromium, whose licence files ship with every installer
(\`LICENSE.electron.txt\` and \`LICENSES.chromium.html\` next to the executable).

## Data

### NCBI data (Pathogen Detection metadata and the AMRFinderPlus Reference Gene Catalog)

Public-domain US Government information. NCBI asks that "NLM be given appropriate acknowledgment", and the
AMRFinderPlus notice asks users to cite Feldgarden et al. See DATA-SOURCES.md for the exact wording and citations.
This app ships only aggregated counts derived from these files, never isolate-level records.

### Natural Earth (world map shapes)

"All versions of Natural Earth raster + vector map data found on this website are in the public domain."
(https://www.naturalearthdata.com/about/terms-of-use/). "Made with Natural Earth." The shapes reach the app through
the \`world-atlas\` package (ISC licence, text below).

### Unicode CLDR (English country names)

Country names come from the Unicode Common Locale Data Repository, used under the Unicode License v3, reproduced in full:

\`\`\`text
${unicode}
\`\`\`

### Not included

The Comprehensive Antibiotic Resistance Database (CARD) is **not** included; its terms do not allow redistribution.

## Libraries bundled in the app

${sections.join("\n\n")}
`;
writeFileSync(join(root, "THIRD-PARTY-NOTICES.md"), out);
console.log(
  `Wrote THIRD-PARTY-NOTICES.md (${String(out.split("\n").length)} lines, ${String(packages.length)} packages)`,
);
